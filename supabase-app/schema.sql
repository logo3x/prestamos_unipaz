-- =============================================================================
-- Préstamo de Videobeams · UNIPAZ — esquema para Supabase
-- -----------------------------------------------------------------------------
-- Ejecutar completo en: Supabase > SQL Editor > New query > Run.
-- Es re-ejecutable: no borra datos existentes.
--
-- La página index.html es pública y la clave de Supabase también, así que toda
-- la seguridad vive aquí:
--   * RLS en todas las tablas.
--   * Las solicitudes solo se escriben a través de funciones (RPC) que validan
--     permisos, anticipación mínima y disponibilidad.
--   * La restricción EXCLUDE de `solicitudes` impide que un videobeam quede
--     reservado dos veces en horarios que se cruzan, incluso con peticiones
--     simultáneas.
--   * Un trigger en auth.users rechaza correos fuera del dominio institucional,
--     tanto para Google como para usuario y contraseña.
--
-- Para dar permisos de administrador (después de que el usuario exista):
--   update public.perfiles set es_admin = true where email = 'admin@unipaz.edu.co';
-- =============================================================================

create extension if not exists btree_gist with schema extensions;


-- =============================================================================
-- Tablas
-- =============================================================================

-- Una sola fila. Se edita desde Supabase > Table Editor.
create table if not exists public.configuracion (
    id boolean primary key default true check (id),
    dominio_institucional text not null default 'unipaz.edu.co',
    dias_anticipacion integer not null default 1 check (dias_anticipacion >= 0),
    zona_horaria text not null default 'America/Bogota'
);

insert into public.configuracion (id) values (true) on conflict (id) do nothing;

create table if not exists public.perfiles (
    id uuid primary key references auth.users (id) on delete cascade,
    nombre text not null,
    email text not null unique,
    avatar_url text,
    es_admin boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.sedes (
    id bigint generated by default as identity primary key,
    nombre text not null check (length(trim(nombre)) between 1 and 255),
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.programas (
    id bigint generated by default as identity primary key,
    nombre text not null check (length(trim(nombre)) between 1 and 255),
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.asignaturas (
    id bigint generated by default as identity primary key,
    nombre text not null check (length(trim(nombre)) between 1 and 255),
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.equipos (
    id bigint generated by default as identity primary key,
    codigo text not null unique check (length(trim(codigo)) between 1 and 50),
    nombre text check (length(nombre) <= 255),
    sede_id bigint references public.sedes (id) on delete set null,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.solicitudes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.perfiles (id),
    sede_id bigint not null references public.sedes (id),
    aula text not null check (length(trim(aula)) between 1 and 255),
    programa_id bigint not null references public.programas (id),
    asignatura_id bigint not null references public.asignaturas (id),
    actividad text check (length(actividad) <= 255),
    fecha date not null,
    hora_inicio time not null,
    hora_fin time not null,
    equipo_id bigint not null references public.equipos (id),
    evidencia_path text,
    observaciones text check (length(observaciones) <= 1000),
    estado text not null default 'confirmada'
        check (estado in ('pendiente', 'confirmada', 'cancelada', 'rechazada')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint solicitudes_horario_valido check (hora_fin > hora_inicio),

    -- Un equipo no puede tener dos solicitudes activas que se crucen en el tiempo.
    constraint solicitudes_sin_solapes exclude using gist (
        equipo_id with =,
        tsrange(fecha + hora_inicio, fecha + hora_fin, '[)') with &&
    ) where (estado in ('pendiente', 'confirmada'))
);

create index if not exists solicitudes_user_id_idx on public.solicitudes (user_id);
create index if not exists solicitudes_fecha_idx on public.solicitudes (fecha);


