insert into public.equipos (codigo, sede_id)
select
    'VB-' || lpad(n::text, 2, '0'),
    (select s.id from public.sedes s where s.nombre = 'Sede Principal' order by s.id limit 1)
from generate_series(1, 8) as n
on conflict (codigo) do nothing;
