-- Fecha actual en la zona horaria de la institución (no en UTC).
create or replace function public.hoy()
returns date
language sql
stable
set search_path = ''
as $$
    select (now() at time zone (select c.zona_horaria from public.configuracion c))::date;
$$;

-- SECURITY DEFINER para poder usarla dentro de las políticas de `perfiles`
-- sin caer en recursión de RLS.
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce((select p.es_admin from public.perfiles p where p.id = auth.uid()), false);
$$;

create or replace function public.actualizar_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();

    return new;
