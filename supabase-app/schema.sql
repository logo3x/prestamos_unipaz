insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('evidencias', 'evidencias', false, 4194304, array['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/bmp'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- Cada usuario sube a su carpeta: evidencias/<user_id>/archivo.jpg
drop policy if exists "evidencias: subir en carpeta propia" on storage.objects;
create policy "evidencias: subir en carpeta propia" on storage.objects
    for insert to authenticated
    with check (bucket_id = 'evidencias' and (storage.foldername(name))[1] = (select auth.uid()::text));

drop policy if exists "evidencias: ver propias o admin" on storage.objects;
create policy "evidencias: ver propias o admin" on storage.objects
    for select to authenticated
    using (
        bucket_id = 'evidencias'
        and ((storage.foldername(name))[1] = (select auth.uid()::text) or (select public.es_admin()))
    );

-- Solo se pueden borrar archivos propios que ninguna solicitud usa (limpieza
-- cuando falla el guardado después de subir la imagen).
drop policy if exists "evidencias: borrar propias sin usar" on storage.objects;
create policy "evidencias: borrar propias sin usar" on storage.objects
    for delete to authenticated
    using (
        bucket_id = 'evidencias'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
        and not exists (select 1 from public.solicitudes s where s.evidencia_path = objects.name)
    );


