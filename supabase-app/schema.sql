-- Crea (p_id = null) o edita una solicitud. Si p_equipo_id es null asigna el
-- primer videobeam activo libre en ese horario.
-- Los errores de validación llevan en DETAIL el nombre del campo afectado.
create or replace function public.guardar_solicitud(
    p_id bigint,
    p_sede_id bigint,
    p_aula text,
    p_programa_id bigint,
    p_asignatura_id bigint,
    p_actividad text,
    p_fecha date,
    p_hora_inicio time,
    p_hora_fin time,
    p_equipo_id bigint,
    p_evidencia_path text,
    p_observaciones text
)
returns public.solicitudes
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_usuario uuid := auth.uid();
    v_existente public.solicitudes;
    v_fecha_minima date := public.hoy() + (select c.dias_anticipacion from public.configuracion c);
    v_equipo_id bigint;
    v_resultado public.solicitudes;
begin
    if v_usuario is null then
        raise exception 'Debes iniciar sesión.' using errcode = '42501';
    end if;

    if p_id is not null then
        select * into v_existente from public.solicitudes s where s.id = p_id for update;

        if not found then
            raise exception 'La solicitud no existe.';
        end if;

        if not (
            public.es_admin()
            or (v_existente.user_id = v_usuario and v_existente.estado = 'confirmada' and v_existente.fecha > public.hoy())
        ) then
            raise exception 'No tienes permiso para editar esta solicitud.' using errcode = '42501';
        end if;
    end if;

    p_aula := nullif(trim(p_aula), '');
    p_actividad := nullif(trim(p_actividad), '');
    p_observaciones := nullif(trim(p_observaciones), '');

    if p_sede_id is null then
        raise exception 'Seleccione una sede.' using detail = 'sede_id';
    end if;

    if p_aula is null then
        raise exception 'Indique el aula.' using detail = 'aula';
    end if;

    if p_programa_id is null then
        raise exception 'Seleccione un programa.' using detail = 'programa_id';
    end if;

    if p_asignatura_id is null then
        raise exception 'Seleccione una asignatura.' using detail = 'asignatura_id';
    end if;

    if p_fecha is null or p_fecha < v_fecha_minima then
        raise exception 'La fecha debe ser igual o posterior al %.', to_char(v_fecha_minima, 'DD/MM/YYYY')
            using detail = 'fecha';
    end if;

    if p_hora_inicio is null then
        raise exception 'Indique la hora de inicio.' using detail = 'hora_inicio';
    end if;

    if p_hora_fin is null or p_hora_fin <= p_hora_inicio then
        raise exception 'La hora de finalización debe ser posterior a la de inicio.' using detail = 'hora_fin';
    end if;

    -- Una evidencia nueva debe estar en la carpeta del usuario que guarda.
    if p_evidencia_path is not null
        and p_evidencia_path is distinct from v_existente.evidencia_path
        and split_part(p_evidencia_path, '/', 1) <> v_usuario::text then
        raise exception 'La evidencia no es válida.' using detail = 'evidencia';
    end if;

    if p_equipo_id is not null and not exists (
        select 1
        from public.equipos e
        where e.id = p_equipo_id
          and (e.activo or e.id = v_existente.equipo_id)
    ) then
        raise exception 'El videobeam seleccionado no está disponible.' using detail = 'equipo_id';
    end if;

    -- La restricción solicitudes_sin_solapes decide si el equipo está libre:
    -- si choca, se prueba el siguiente equipo.
    for v_equipo_id in
        select e.id
        from public.equipos e
        where case when p_equipo_id is null then e.activo else e.id = p_equipo_id end
        order by e.id
    loop
        begin
            if p_id is null then
                insert into public.solicitudes (
                    user_id, sede_id, aula, programa_id, asignatura_id, actividad,
                    fecha, hora_inicio, hora_fin, equipo_id, evidencia_path, observaciones, estado
                )
                values (
                    v_usuario, p_sede_id, p_aula, p_programa_id, p_asignatura_id, p_actividad,
                    p_fecha, p_hora_inicio, p_hora_fin, v_equipo_id, p_evidencia_path, p_observaciones, 'confirmada'
                )
                returning * into v_resultado;
            else
                update public.solicitudes s
                set sede_id = p_sede_id,
                    aula = p_aula,
                    programa_id = p_programa_id,
                    asignatura_id = p_asignatura_id,
                    actividad = p_actividad,
                    fecha = p_fecha,
                    hora_inicio = p_hora_inicio,
                    hora_fin = p_hora_fin,
                    equipo_id = v_equipo_id,
                    evidencia_path = coalesce(p_evidencia_path, s.evidencia_path),
                    observaciones = p_observaciones
                where s.id = p_id
                returning * into v_resultado;
            end if;

            return v_resultado;
        exception
            when exclusion_violation then
                null;
        end;
    end loop;

    if p_equipo_id is not null then
        raise exception 'Ese equipo ya está reservado en el horario seleccionado.' using detail = 'equipo_id';
    end if;

    raise exception 'No hay videobeams disponibles en el horario seleccionado.' using detail = 'equipo_id';
end;
$$;

-- El docente cancela su propia solicitud activa con fecha futura.
create or replace function public.cancelar_solicitud(p_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_solicitud public.solicitudes;
begin
    select * into v_solicitud from public.solicitudes s where s.id = p_id for update;

    if not found or v_solicitud.user_id is distinct from auth.uid() then
        raise exception 'No tienes permiso para cancelar esta solicitud.' using errcode = '42501';
    end if;

    if v_solicitud.estado not in ('pendiente', 'confirmada') or v_solicitud.fecha <= public.hoy() then
        raise exception 'Esta solicitud ya no se puede cancelar.';
    end if;

    update public.solicitudes s set estado = 'cancelada' where s.id = p_id;
end;
$$;

-- El admin cambia el estado de cualquier solicitud.
create or replace function public.cambiar_estado_solicitud(p_id bigint, p_estado text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not public.es_admin() then
        raise exception 'Solo un administrador puede cambiar el estado.' using errcode = '42501';
    end if;

    if p_estado is null or p_estado not in ('pendiente', 'confirmada', 'cancelada', 'rechazada') then
        raise exception 'Estado no válido.';
    end if;

    update public.solicitudes s set estado = p_estado where s.id = p_id;

    if not found then
        raise exception 'La solicitud no existe.';
    end if;
exception
    when exclusion_violation then
        raise exception 'No se puede cambiar el estado: ese equipo ya está reservado en ese horario.';
end;
$$;

-- Reservas activas para el calendario entre p_inicio (incluido) y p_fin
-- (excluido, como lo envía FullCalendar). Expone solo lo necesario de las
-- solicitudes de otros docentes (no aula, observaciones ni evidencia).
create or replace function public.eventos_calendario(p_inicio date, p_fin date)
returns table (
    id bigint,
    fecha date,
    hora_inicio time,
    hora_fin time,
    estado text,
    equipo_id bigint,
    equipo text,
    asignatura text,
    docente text
)
language sql
stable
security definer
set search_path = ''
as $$
    select s.id, s.fecha, s.hora_inicio, s.hora_fin, s.estado, s.equipo_id, e.codigo, a.nombre, p.nombre
    from public.solicitudes s
    join public.equipos e on e.id = s.equipo_id
    join public.asignaturas a on a.id = s.asignatura_id
    join public.perfiles p on p.id = s.user_id
    where auth.uid() is not null
      and s.estado in ('pendiente', 'confirmada')
      and s.fecha >= p_inicio
      and s.fecha < p_fin;
$$;

revoke execute on function
    public.guardar_solicitud,
    public.cancelar_solicitud,
    public.cambiar_estado_solicitud,
    public.eventos_calendario
from public, anon;

grant execute on function
    public.guardar_solicitud,
    public.cancelar_solicitud,
    public.cambiar_estado_solicitud,
    public.eventos_calendario
to authenticated;


