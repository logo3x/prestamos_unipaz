-- La página de login necesita el dominio antes de que exista una sesión.
drop policy if exists "configuracion: lectura pública" on public.configuracion;
create policy "configuracion: lectura pública" on public.configuracion
    for select to anon, authenticated
    using (true);

-- Nadie edita perfiles desde la página (es_admin se cambia por SQL).
drop policy if exists "perfiles: ver el propio o admin" on public.perfiles;
create policy "perfiles: ver el propio o admin" on public.perfiles
    for select to authenticated
    using (id = (select auth.uid()) or (select public.es_admin()));

-- Catálogos: cualquier usuario autenticado los lee; solo admin crea y edita.
do $$
declare
    v_tabla text;
begin
    foreach v_tabla in array array['sedes', 'programas', 'asignaturas', 'equipos'] loop
        execute format('drop policy if exists "%1$s: lectura" on public.%1$I', v_tabla);
        execute format(
            'create policy "%1$s: lectura" on public.%1$I for select to authenticated using (true)',
            v_tabla
        );

        execute format('drop policy if exists "%1$s: admin crea" on public.%1$I', v_tabla);
        execute format(
            'create policy "%1$s: admin crea" on public.%1$I for insert to authenticated with check ((select public.es_admin()))',
            v_tabla
        );

        execute format('drop policy if exists "%1$s: admin edita" on public.%1$I', v_tabla);
        execute format(
            'create policy "%1$s: admin edita" on public.%1$I for update to authenticated using ((select public.es_admin())) with check ((select public.es_admin()))',
            v_tabla
        );
    end loop;
end;
$$;

-- Solicitudes: cada docente ve las suyas y el admin ve todas. No hay políticas
-- de escritura: se crean, editan y cancelan solo mediante las funciones de abajo.
drop policy if exists "solicitudes: ver propias o admin" on public.solicitudes;
create policy "solicitudes: ver propias o admin" on public.solicitudes
    for select to authenticated
    using (user_id = (select auth.uid()) or (select public.es_admin()));

revoke insert, update, delete on public.configuracion, public.perfiles, public.solicitudes from anon, authenticated;


