-- =============================================================================
-- Registro de usuarios: solo dominio institucional
-- =============================================================================

-- Se ejecuta al crear cualquier usuario en Supabase Auth (Google, contraseña o
-- desde el panel). Si el correo no es institucional, la creación falla.
create or replace function public.registrar_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_dominio text := (select c.dominio_institucional from public.configuracion c);
begin
    if lower(split_part(coalesce(new.email, ''), '@', 2)) is distinct from lower(v_dominio) then
        raise exception 'Solo se permiten correos institucionales @%', v_dominio;
    end if;

    insert into public.perfiles (id, nombre, email, avatar_url)
    values (
        new.id,
        coalesce(
            nullif(new.raw_user_meta_data ->> 'full_name', ''),
            nullif(new.raw_user_meta_data ->> 'name', ''),
            split_part(new.email, '@', 1)
        ),
        new.email,
        coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture')
    );

    return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario
    after insert on auth.users
    for each row execute function public.registrar_perfil();

-- Crea el perfil de usuarios institucionales que ya existían antes de este script.
insert into public.perfiles (id, nombre, email, avatar_url)
select
    u.id,
    coalesce(
        nullif(u.raw_user_meta_data ->> 'full_name', ''),
        nullif(u.raw_user_meta_data ->> 'name', ''),
        split_part(u.email, '@', 1)
    ),
    u.email,
    coalesce(u.raw_user_meta_data ->> 'avatar_url', u.raw_user_meta_data ->> 'picture')
from auth.users u
where lower(split_part(u.email, '@', 2)) = (select lower(c.dominio_institucional) from public.configuracion c)
on conflict (id) do nothing;


